import "server-only";
import { PDFDocument, StandardFonts, degrees, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import type { FinanceDocument } from "@/lib/types";
import type { FinancialReport } from "@/server/engines/ledger";

const INK = rgb(0.1, 0.13, 0.11);
const MUTED = rgb(0.4, 0.44, 0.41);
const BRAND = rgb(0.12, 0.36, 0.26);
const RULE = rgb(0.87, 0.87, 0.84);

/** pdf-lib's standard fonts are WinAnsi-only; normalise typography that would otherwise throw. */
function safe(s: string): string {
  return s.replace(/[–—]/g, "-").replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/•/g, "*").replace(/−/g, "-").replace(/×/g, "x").replace(/[^\x20-\x7E\xA0-\xFF]/g, "");
}

const fmt = (c: number) => {
  const v = Math.round(c / 100);
  const s = Math.abs(v).toLocaleString("en-US");
  return v < 0 ? `(${s})` : s;
};
const fmt2 = (c: number) => `$${(c / 100).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

class Writer {
  doc!: PDFDocument;
  page!: PDFPage;
  font!: PDFFont;
  bold!: PDFFont;
  y = 0;
  readonly w = 612;
  readonly h = 792;
  readonly m = 48;
  footer = "";
  static async create(footer: string) {
    const w = new Writer();
    w.doc = await PDFDocument.create();
    w.font = await w.doc.embedFont(StandardFonts.Helvetica);
    w.bold = await w.doc.embedFont(StandardFonts.HelveticaBold);
    w.footer = footer;
    w.newPage();
    return w;
  }
  newPage() {
    this.page = this.doc.addPage([this.w, this.h]);
    this.y = this.h - this.m;
    this.page.drawText(safe(this.footer), { x: this.m, y: 24, size: 7.5, font: this.font, color: MUTED });
  }
  ensure(space: number) {
    if (this.y - space < 48) this.newPage();
  }
  text(s: string, opts: { size?: number; bold?: boolean; color?: ReturnType<typeof rgb>; x?: number; right?: number } = {}) {
    const size = opts.size ?? 10;
    const font = opts.bold ? this.bold : this.font;
    const str = safe(s);
    const x = opts.right != null ? opts.right - font.widthOfTextAtSize(str, size) : (opts.x ?? this.m);
    this.page.drawText(str, { x, y: this.y, size, font, color: opts.color ?? INK });
  }
  line(gap = 14) {
    this.y -= gap;
  }
  rule(color = RULE) {
    this.page.drawLine({ start: { x: this.m, y: this.y + 4 }, end: { x: this.w - this.m, y: this.y + 4 }, thickness: 0.6, color });
  }
  wrap(s: string, size = 10, width = 612 - 96) {
    const words = safe(s).split(/\s+/);
    let cur = "";
    for (const w of words) {
      const next = cur ? `${cur} ${w}` : w;
      if (this.font.widthOfTextAtSize(next, size) > width) {
        this.ensure(14);
        this.text(cur, { size });
        this.line(size + 4);
        cur = w;
      } else cur = next;
    }
    if (cur) {
      this.ensure(14);
      this.text(cur, { size });
      this.line(size + 4);
    }
  }
}

export async function reportPdf(report: FinancialReport, orgName: string, generatedAt: string): Promise<Uint8Array> {
  const w = await Writer.create(`${orgName} · ${report.title} · Generated by Fabrik Finance ${generatedAt.slice(0, 16).replace("T", " ")} UTC · Source: QuickBooks Online`);
  writeReport(w, report, orgName);
  return w.doc.save();
}

function writeReport(w: Writer, report: FinancialReport, orgName: string) {
  w.text(orgName, { size: 9, color: MUTED });
  w.line(18);
  w.text(report.title, { size: 18, bold: true, color: BRAND });
  w.line(16);
  w.text(`${report.subtitle} · ${report.basis === "accrual" ? "Accrual basis" : "Cash basis"}`, { size: 9, color: MUTED });
  w.line(24);
  const cols = report.columns.slice(-6);
  const offset = report.columns.length - cols.length;
  const colW = 70;
  const right = w.w - w.m;
  cols.forEach((c, i) => w.text(c.label, { size: 8, bold: true, right: right - (cols.length - 1 - i) * colW, color: MUTED }));
  w.line(8);
  w.rule();
  w.line(8);
  for (const l of report.lines) {
    if (l.kind === "spacer") {
      w.line(6);
      continue;
    }
    w.ensure(16);
    const bold = l.kind !== "account";
    w.text(l.label, { size: l.kind === "grand" ? 10.5 : 9, bold, x: w.m + l.depth * 12 });
    if (l.kind !== "header") cols.forEach((_, i) => w.text(fmt(l.values[offset + i] ?? 0), { size: 9, bold, right: right - (cols.length - 1 - i) * colW }));
    if (l.kind === "total" || l.kind === "grand") {
      w.line(4);
      w.rule(l.kind === "grand" ? INK : RULE);
      w.line(10);
    } else w.line(14);
  }
  for (const c of report.checks) {
    w.line(6);
    w.text(`${c.ok ? "OK" : "!"} ${c.label}: ${c.detail ?? ""}`, { size: 8, color: MUTED });
  }
}

export interface PackageSection {
  heading: string;
  paragraphs?: string[];
  bullets?: string[];
  table?: { columns: string[]; rows: string[][] };
}

export async function packagePdf(title: string, orgName: string, sections: PackageSection[], reports: FinancialReport[]): Promise<Uint8Array> {
  const w = await Writer.create(`${orgName} · ${title} · Fabrik Finance`);
  w.text("MONTHLY FINANCE PACKAGE", { size: 9, bold: true, color: BRAND });
  w.line(22);
  w.text(title, { size: 22, bold: true });
  w.line(18);
  w.text(orgName, { size: 11, color: MUTED });
  w.line(28);
  for (const s of sections) {
    w.ensure(60);
    w.text(s.heading, { size: 13, bold: true, color: BRAND });
    w.line(18);
    for (const p of s.paragraphs ?? []) w.wrap(p);
    for (const b of s.bullets ?? []) w.wrap(`- ${b}`);
    if (s.table) {
      const colW = (w.w - 2 * w.m) / s.table.columns.length;
      s.table.columns.forEach((c, i) => w.text(c, { size: 8, bold: true, color: MUTED, x: w.m + i * colW }));
      w.line(12);
      for (const r of s.table.rows) {
        w.ensure(14);
        r.forEach((c, i) => w.text(c.slice(0, 38), { size: 8.5, x: w.m + i * colW }));
        w.line(12);
      }
    }
    w.line(10);
  }
  for (const r of reports) {
    w.newPage();
    writeReport(w, r, orgName);
  }
  return w.doc.save();
}

/** Renders a seeded document (no original file) from its extracted fields, clearly marked synthetic. */
export async function syntheticDocumentPdf(d: FinanceDocument, orgLegalName: string): Promise<Uint8Array> {
  const w = await Writer.create("SYNTHETIC DEMO DOCUMENT - generated from seeded data, not an original record");
  const e = d.extraction;
  w.page.drawText("SYNTHETIC", { x: 150, y: 380, size: 90, font: w.bold, color: rgb(0.93, 0.95, 0.93), rotate: degrees(30) });
  w.text(e?.vendor ?? d.filename, { size: 16, bold: true });
  w.line(30);
  const title = d.kind === "receipt" ? "RECEIPT" : d.kind.includes("statement") ? "ACCOUNT STATEMENT" : d.kind === "invoice" ? "INVOICE" : d.kind.replace(/_/g, " ").toUpperCase();
  w.text(title, { size: 20, bold: true, color: BRAND });
  w.line(28);
  if (e?.documentNumber) (w.text(`Number: ${e.documentNumber}`), w.line());
  if (e?.documentDate) (w.text(`Date: ${e.documentDate}`), w.line());
  if (e?.dueDate) (w.text(`Due Date: ${e.dueDate}`), w.line());
  w.text(`Bill To: ${orgLegalName}`);
  w.line(26);
  for (const li of e?.lineItems ?? []) {
    w.text(li.description, { size: 9 });
    w.text(fmt2(li.amount), { size: 9, right: w.w - w.m });
    w.line();
  }
  if (e?.subtotal != null) (w.text("Subtotal"), w.text(fmt2(e.subtotal), { right: w.w - w.m }), w.line());
  if (e?.tax) (w.text("Tax"), w.text(fmt2(e.tax), { right: w.w - w.m }), w.line());
  if (e?.total != null) {
    w.rule();
    w.line(6);
    w.text("Total", { bold: true });
    w.text(fmt2(e.total), { bold: true, right: w.w - w.m });
    w.line(30);
  }
  if (!e) w.wrap(`${d.filename} — stored document for ${orgLegalName}. This seeded record has no original file.`);
  return w.doc.save();
}

